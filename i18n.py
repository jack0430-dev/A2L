def set_language(lang):
    """切换当前语言，返回生效的语言代码。"""
    global LANG
    LANG = lang if lang in ("en", "zh") else DEFAULT_LANG
    return LANG


def get_language():
    return LANG


def is_chinese():
    return LANG == "zh"


def tr(key, **kwargs):
    """取当前语言的文案。key 为英文原文；缺译时回落英文原文。"""
    text = ZH.get(key, key) if LANG == "zh" else key
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, IndexError, ValueError):
            return text
    return text


def tf(key, **kwargs):
    """带占位符的动态文案（模板 key 中的占位符用 {name} 形式）。"""
    return tr(key, **kwargs)
